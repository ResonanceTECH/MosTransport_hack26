# Relative demand by position along the route: termini and the middle interchange
# carry more boardings than the stops in between.
def _load_weights(count: int) -> list[float]:
    raw = []
    for index in range(count):
        position = index / max(count - 1, 1)
        terminus = math.exp(-((position - 0.0) ** 2) / 0.05) + math.exp(-((position - 1.0) ** 2) / 0.05)
        middle = 0.8 * math.exp(-((position - 0.5) ** 2) / 0.08)
        raw.append(0.45 + terminus + middle)
    total = sum(raw)
    return [value / total for value in raw]


def stop_id(route_id: int, sequence: int) -> str:
    return f"S{route_id:02d}{sequence:02d}"


def routes() -> list[dict]:
    return [
        {"route_id": route_id, "number": number, "name": name, "color": color}
        for route_id, (number, name, color, _) in sorted(ROUTE_CORRIDORS.items())
    ]


def stops() -> list[dict]:
    rows = []
    for route_id, (_, _, _, corridor) in sorted(ROUTE_CORRIDORS.items()):
        weights = _load_weights(len(corridor))
        for index, ((name, lat, lon), weight) in enumerate(zip(corridor, weights), start=1):
            rows.append({
                "stop_id": stop_id(route_id, index),
                "route_id": route_id,
                "name": name,
                "latitude": lat,
                "longitude": lon,
                "sequence": index,
                "load_weight": round(weight, 6),
            })
    return rows


def geometries() -> list[dict]:
    rows = []
    for route_id, (_, _, _, corridor) in sorted(ROUTE_CORRIDORS.items()):
        coordinates = [[lon, lat] for _, lat, lon in corridor]
        rows.append({
            "route_id": route_id,
            "geometry": {"type": "LineString", "coordinates": coordinates},
        })
    return rows
